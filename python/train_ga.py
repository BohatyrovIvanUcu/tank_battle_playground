#!/usr/bin/env python3
"""
Example trainer (genetic algorithm + SimpleMLP). Replace it with whatever you like -
the only thing the playground needs from you is an agent file (see tank_env/agent.py).

This one writes `<save-dir>/best_model.npz` and `<save-dir>/agent.py`, so the result can go
straight into the referee:  python python/referee.py checkpoints/agent.py rule_based
"""
import argparse
import os
import random
import time
import numpy as np

from tank_env import (
    TankEnvironment,
    VectorObservationAdapter,
    LidarObservationAdapter,
    MLPAgent,
    SimpleMLP,
    load_agent,
    reset_agent,
)

AGENT_FILE_TEMPLATE = '''"""Auto-generated by train_ga.py - drop this file (and best_model.npz) into the referee."""
from pathlib import Path
from tank_env import MLPAgent, {adapter}


def make_agent():
    return MLPAgent.load(Path(__file__).parent / "best_model.npz", {adapter}())
'''


class GAPopulation:
    def __init__(
        self,
        pop_size: int,
        input_dim: int,
        hidden_dims: list,
        output_dim: int = 4,
        mutation_rate: float = 0.10,
        mutation_power: float = 0.20,
        elitism_ratio: float = 0.15,
    ):
        self.pop_size = pop_size
        self.input_dim = input_dim
        self.hidden_dims = hidden_dims
        self.output_dim = output_dim
        self.mutation_rate = mutation_rate
        self.mutation_power = mutation_power
        self.elitism_ratio = elitism_ratio

        self.population: list[SimpleMLP] = [
            SimpleMLP(input_dim, hidden_dims, output_dim) for _ in range(pop_size)
        ]

    def mutate(self, chromosome: np.ndarray) -> np.ndarray:
        mutated = chromosome.copy()
        mask = np.random.rand(len(mutated)) < self.mutation_rate
        noise = np.random.randn(len(mutated)) * self.mutation_power
        mutated += mask * noise
        return mutated.astype(np.float32)

    def crossover(self, parent1: np.ndarray, parent2: np.ndarray) -> np.ndarray:
        # Uniform blend crossover
        alpha = np.random.uniform(0.0, 1.0, size=len(parent1)).astype(np.float32)
        child = alpha * parent1 + (1.0 - alpha) * parent2
        return child

    def evolve(self, fitnesses: list[float]) -> tuple[SimpleMLP, float, float]:
        sorted_indices = np.argsort(fitnesses)[::-1]
        best_idx = sorted_indices[0]
        best_individual = self.population[best_idx]
        best_fitness = fitnesses[best_idx]
        mean_fitness = float(np.mean(fitnesses))

        num_elites = max(1, int(self.pop_size * self.elitism_ratio))
        new_population = []

        # 1. Elitism
        for i in range(num_elites):
            elite_model = SimpleMLP(self.input_dim, self.hidden_dims, self.output_dim)
            elite_model.set_chromosome(self.population[sorted_indices[i]].get_chromosome().copy())
            new_population.append(elite_model)

        # 2. Tournament selection & reproduction
        tournament_k = min(3, self.pop_size)
        while len(new_population) < self.pop_size:
            t1 = random.sample(range(self.pop_size), tournament_k)
            t2 = random.sample(range(self.pop_size), tournament_k)
            p1_idx = max(t1, key=lambda idx: fitnesses[idx])
            p2_idx = max(t2, key=lambda idx: fitnesses[idx])

            c1 = self.population[p1_idx].get_chromosome()
            c2 = self.population[p2_idx].get_chromosome()

            child_chrom = self.mutate(self.crossover(c1, c2))

            child_model = SimpleMLP(self.input_dim, self.hidden_dims, self.output_dim)
            child_model.set_chromosome(child_chrom)
            new_population.append(child_model)

        self.population = new_population
        return best_individual, best_fitness, mean_fitness


def evaluate_individual(model: SimpleMLP, adapter, opponent, env: TankEnvironment, seeds) -> float:
    """
    Mean reward over one game per seed. Odd games put the model on tank 2, so it learns
    to play both sides. Every individual of a generation gets the same seeds (same maps),
    which keeps fitness values comparable inside the generation.
    """
    agent = MLPAgent(model, adapter)
    total = 0.0
    for i, seed in enumerate(seeds):
        me = i % 2  # 0 = tank 1, 1 = tank 2
        reset_agent(opponent)
        obs = list(env.reset(seed=seed))
        done = False
        while not done:
            mine, theirs = agent.act(obs[me]), opponent.act(obs[1 - me])
            actions = (mine, theirs) if me == 0 else (theirs, mine)
            obs1, obs2, rewards, done, _ = env.step(*actions)
            obs = [obs1, obs2]
            total += rewards[me]
    return total / len(seeds)


def write_agent_file(save_dir: str, adapter_cls) -> None:
    with open(os.path.join(save_dir, "agent.py"), "w") as f:
        f.write(AGENT_FILE_TEMPLATE.format(adapter=adapter_cls.__name__))


def main():
    parser = argparse.ArgumentParser(description="Train a tank agent with a genetic algorithm")
    parser.add_argument("--generations", type=int, default=10)
    parser.add_argument("--population", type=int, default=20)
    parser.add_argument("--rounds", type=int, default=4, help="games (= different maps) per individual per generation")
    parser.add_argument("--adapter", choices=["vector", "lidar"], default="vector")
    parser.add_argument("--opponent", default="rule_based",
                        help="'rule_based', 'random', an agent .py file (e.g. your friend's), "
                             "or 'self' = best of the previous generation")
    parser.add_argument("--val-maps", type=int, default=8,
                        help="fixed validation maps; the checkpoint is chosen by score on these, not by lucky training maps")
    parser.add_argument("--max-steps", type=int, default=800,
                        help="episode length while training (the referee always uses the official 1500)")
    parser.add_argument("--seed", type=int, default=None, help="makes the run reproducible")
    parser.add_argument("--save-dir", default="checkpoints")
    args = parser.parse_args()

    if args.seed is not None:
        random.seed(args.seed)
        np.random.seed(args.seed)
    map_rng = random.Random(args.seed)
    os.makedirs(args.save_dir, exist_ok=True)

    adapter_cls = VectorObservationAdapter if args.adapter == "vector" else LidarObservationAdapter
    adapter = adapter_cls()
    self_play = args.opponent == "self"
    opponent = load_agent("rule_based" if self_play else args.opponent)

    print("=========================================================")
    print(" Genetic Algorithm training for 2D Tanks")
    print(f" - Generations: {args.generations}   Population: {args.population}   Maps/gen: {args.rounds}")
    print(f" - Adapter:     {args.adapter} (dim={adapter.output_dim})")
    print(f" - Opponent:    {args.opponent}")
    print(f" - Save dir:    {args.save_dir}")
    print("=========================================================")

    env = TankEnvironment(max_steps=args.max_steps)
    ga = GAPopulation(args.population, adapter.output_dim, [24, 24], 4)

    best_overall = -float("inf")  # best validation score (or last best fitness in self-play)
    val_seeds = [10_000_000 + i for i in range(args.val_maps)]  # same maps every generation
    model_path = os.path.join(args.save_dir, "best_model.npz")
    start = time.time()
    for gen in range(1, args.generations + 1):
        seeds = [map_rng.randrange(1_000_000_000) for _ in range(args.rounds)]
        fitnesses = [evaluate_individual(ind, adapter, opponent, env, seeds) for ind in ga.population]

        best_ind, best_fit, mean_fit = ga.evolve(fitnesses)
        line = f"Gen {gen:03d}/{args.generations:03d} | Best: {best_fit:8.2f} | Mean: {mean_fit:8.2f}"

        # Training maps change every generation, so "best fitness" is partly luck. Against a fixed
        # opponent the checkpoint is chosen by the generation's best on the fixed validation maps.
        if self_play:
            best_overall = best_fit
            best_ind.save(model_path)
        else:
            val = evaluate_individual(best_ind, adapter, opponent, env, val_seeds)
            line += f" | Val: {val:8.2f}"
            if val > best_overall:
                best_overall = val
                best_ind.save(model_path)
                line += " *"
        print(line)
        if self_play:
            opponent = MLPAgent(best_ind, adapter)  # next generation fights this one
        if gen % 5 == 0 or gen == args.generations:
            best_ind.save(os.path.join(args.save_dir, f"model_gen_{gen}.npz"))

    write_agent_file(args.save_dir, adapter_cls)
    print("=========================================================")
    print(f" Done in {time.time() - start:.1f}s. Best {"fitness" if self_play else "validation score"}: {best_overall:.2f}")
    print(f" Agent: {os.path.join(args.save_dir, 'agent.py')}  (model: {model_path})")
    print(f" Test it: python python/referee.py {os.path.join(args.save_dir, 'agent.py')} rule_based")
    print("=========================================================")


if __name__ == "__main__":
    main()
