#!/usr/bin/env python3
"""
Example trainer (genetic algorithm + SimpleMLP). Replace it with whatever you like -
the only thing the playground needs from you is an agent file (see tank_env/agent.py).

This one writes `<save-dir>/best_model.npz` and `<save-dir>/agent.py`, so the result can go
straight into the referee:  python python/referee.py checkpoints/agent.py rule_based
"""
import argparse
import math
import os
import random
import time
import numpy as np

from tank_env import (
    TankEnvironment,
    VectorObservationAdapter,
    LidarObservationAdapter,
    CombatObservationAdapter,
    MLPAgent,
    SimpleMLP,
    load_agent,
    reset_agent,
)

AGENT_FILE_TEMPLATE = '''"""Auto-generated by train_ga.py - drop this file (and best_model.npz) into the referee."""
from pathlib import Path
from tank_env import MLPAgent, {adapter}


def make_agent():
    return MLPAgent.load(Path(__file__).parent / "best_model.npz", {adapter}())
'''


class GAPopulation:
    def __init__(
        self,
        pop_size: int,
        input_dim: int,
        hidden_dims: list,
        output_dim: int = 4,
        mutation_rate: float = 0.10,
        mutation_power: float = 0.20,
        elitism_ratio: float = 0.15,
    ):
        self.pop_size = pop_size
        self.input_dim = input_dim
        self.hidden_dims = hidden_dims
        self.output_dim = output_dim
        self.mutation_rate = mutation_rate
        self.mutation_power = mutation_power
        self.elitism_ratio = elitism_ratio

        self.population: list[SimpleMLP] = [
            SimpleMLP(input_dim, hidden_dims, output_dim) for _ in range(pop_size)
        ]

    def seed_with_model(self, model: SimpleMLP):
        """Seed population with an existing trained model and its mutations."""
        base_chrom = model.get_chromosome()
        num_elites = max(1, int(self.pop_size * self.elitism_ratio))
        for i in range(num_elites):
            self.population[i].set_chromosome(base_chrom.copy())
        for i in range(num_elites, self.pop_size):
            self.population[i].set_chromosome(self.mutate(base_chrom.copy()))

    def mutate(self, chromosome: np.ndarray) -> np.ndarray:
        mutated = chromosome.copy()
        mask = np.random.rand(len(mutated)) < self.mutation_rate
        noise = np.random.randn(len(mutated)) * self.mutation_power
        mutated += mask * noise
        return mutated.astype(np.float32)

    def crossover(self, parent1: np.ndarray, parent2: np.ndarray) -> np.ndarray:
        # Uniform blend crossover
        alpha = np.random.uniform(0.0, 1.0, size=len(parent1)).astype(np.float32)
        child = alpha * parent1 + (1.0 - alpha) * parent2
        return child

    def evolve(self, fitnesses: list[float]) -> tuple[SimpleMLP, float, float]:
        sorted_indices = np.argsort(fitnesses)[::-1]
        best_idx = sorted_indices[0]
        best_individual = self.population[best_idx]
        best_fitness = fitnesses[best_idx]
        mean_fitness = float(np.mean(fitnesses))

        num_elites = max(1, int(self.pop_size * self.elitism_ratio))
        new_population = []

        # 1. Elitism
        for i in range(num_elites):
            elite_model = SimpleMLP(self.input_dim, self.hidden_dims, self.output_dim)
            elite_model.set_chromosome(self.population[sorted_indices[i]].get_chromosome().copy())
            new_population.append(elite_model)

        # 2. Tournament selection & reproduction
        tournament_k = min(3, self.pop_size)
        while len(new_population) < self.pop_size:
            t1 = random.sample(range(self.pop_size), tournament_k)
            t2 = random.sample(range(self.pop_size), tournament_k)
            p1_idx = max(t1, key=lambda idx: fitnesses[idx])
            p2_idx = max(t2, key=lambda idx: fitnesses[idx])

            c1 = self.population[p1_idx].get_chromosome()
            c2 = self.population[p2_idx].get_chromosome()

            child_chrom = self.mutate(self.crossover(c1, c2))

            child_model = SimpleMLP(self.input_dim, self.hidden_dims, self.output_dim)
            child_model.set_chromosome(child_chrom)
            new_population.append(child_model)

        self.population = new_population
        return best_individual, best_fitness, mean_fitness


def evaluate_individual(model: SimpleMLP, adapter, opponent, env: TankEnvironment, seeds) -> float:
    """
    Mean shaped fitness over one game per seed. Odd games put the model on tank 2, so it
    learns to play both sides. The Rust engine provides fair baseline damage/hit rewards,
    while this Python-side wrapper shapes fitness to eliminate passive camping and teach aiming.
    """
    agent = MLPAgent(model, adapter)
    total = 0.0
    for i, seed in enumerate(seeds):
        me = i % 2  # 0 = tank 1, 1 = tank 2
        opp = opponent[i % len(opponent)] if isinstance(opponent, list) else opponent
        reset_agent(opp)
        obs = list(env.reset(seed=seed))
        prev_dist = float(obs[me].get("enemy_dist", 1.0))
        done = False
        while not done:
            mine, theirs = agent.act(obs[me]), opp.act(obs[1 - me])
            actions = (mine, theirs) if me == 0 else (theirs, mine)
            obs1, obs2, rewards, done, _ = env.step(*actions)

            my_obs = obs1 if me == 0 else obs2
            opp_obs = obs2 if me == 0 else obs1
            r = float(rewards[me])

            # 1. Wall stalling penalty (punish pushing thrust into wall/obstacle without velocity)
            if abs(float(mine[0])) > 0.3 and float(my_obs.get("speed", 0.0)) < 0.2:
                r -= 0.12

            # 2. Active hunting / closing distance incentive
            curr_dist = float(my_obs.get("enemy_dist", 1.0))
            dist_delta = prev_dist - curr_dist  # > 0 means got closer to enemy
            r += dist_delta * 2.5
            prev_dist = curr_dist

            # 3. Turret aiming alignment reward
            aim_aligned = False
            world_enemy_angle = float(my_obs.get("body_angle", 0.0)) + float(my_obs.get("enemy_angle_to", 0.0))
            turret_angle = float(my_obs.get("turret_angle", 0.0))
            align = math.cos(world_enemy_angle - turret_angle)
            if my_obs.get("enemy_visible", False):
                if align > 0.0:
                    r += 0.06 * align
                if align > 0.85:
                    aim_aligned = True

            # 4. Shooting discipline
            if float(mine[3]) > 0.0:
                if my_obs.get("enemy_visible", False) and aim_aligned:
                    r += 0.10  # clean shot on target
                elif not my_obs.get("enemy_visible", False) or align < 0.2:
                    r -= 0.02  # wasted shot into obstacle

            # 5. Direct Kill vs Timeout distinction
            if done:
                opp_hp = float(opp_obs.get("hp", 0.0))
                my_hp = float(my_obs.get("hp", 0.0))
                if opp_hp <= 0.0:
                    # DIRECT KILL: 5x higher bounty bonus!
                    r += 150.0
                elif my_hp <= 0.0:
                    # Defeated
                    r -= 50.0
                else:
                    # Draw / mutual timeout camping penalty
                    r -= 40.0

            total += r
            obs = [obs1, obs2]
    return total / len(seeds)


def write_agent_file(save_dir: str, adapter_cls) -> None:
    with open(os.path.join(save_dir, "agent.py"), "w") as f:
        f.write(AGENT_FILE_TEMPLATE.format(adapter=adapter_cls.__name__))


def write_checkpoint_agent(save_dir: str, adapter_cls, model_filename: str, agent_filename: str) -> None:
    content = f'''"""Auto-generated agent for {model_filename}."""
from pathlib import Path
from tank_env import MLPAgent, {adapter_cls.__name__}


def make_agent():
    return MLPAgent.load(Path(__file__).parent / "{model_filename}", {adapter_cls.__name__}())
'''
    with open(os.path.join(save_dir, agent_filename), "w") as f:
        f.write(content)


def main():
    parser = argparse.ArgumentParser(description="Train a tank agent with a genetic algorithm")
    parser.add_argument("--generations", type=int, default=10)
    parser.add_argument("--population", type=int, default=20)
    parser.add_argument("--rounds", type=int, default=4, help="games (= different maps) per individual per generation")
    parser.add_argument("--adapter", choices=["combat", "vector", "lidar"], default="combat")
    parser.add_argument("--opponent", default="rule_based",
                        help="'rule_based', 'random', an agent .py file (e.g. your friend's), "
                             "or 'self' = best of the previous generation")
    parser.add_argument("--val-maps", type=int, default=8,
                        help="fixed validation maps; the checkpoint is chosen by score on these, not by lucky training maps")
    parser.add_argument("--max-steps", type=int, default=800,
                        help="episode length while training (the referee always uses the official 1500)")
    parser.add_argument("--seed", type=int, default=None, help="makes the run reproducible")
    parser.add_argument("--resume", default=None, help="path to .npz model file to seed population from")
    parser.add_argument("--start-gen", type=int, default=0, help="starting generation counter offset")
    parser.add_argument("--checkpoint-interval", type=int, default=100, help="save checkpoint every N generations")
    parser.add_argument("--save-dir", default="checkpoints")
    args = parser.parse_args()

    if args.seed is not None:
        random.seed(args.seed)
        np.random.seed(args.seed)
    map_rng = random.Random(args.seed)
    os.makedirs(args.save_dir, exist_ok=True)

    if args.adapter == "combat":
        adapter_cls = CombatObservationAdapter
    elif args.adapter == "vector":
        adapter_cls = VectorObservationAdapter
    else:
        adapter_cls = LidarObservationAdapter
    adapter = adapter_cls()
    self_play = args.opponent == "self"
    benchmark_bot = load_agent("rule_based")
    opponent = None if self_play else load_agent(args.opponent)

    total_target_gens = args.start_gen + args.generations
    print("=========================================================")
    print(" Genetic Algorithm training for 2D Tanks")
    print(f" - Generations: {args.generations} (Total target: {total_target_gens})   Population: {args.population}   Maps/gen: {args.rounds}")
    print(f" - Adapter:     {args.adapter} (dim={adapter.output_dim})")
    print(f" - Opponent:    {args.opponent} {'(Self-Play Co-Evolution)' if self_play else ''}")
    print(f" - Save dir:    {args.save_dir}")
    if args.resume:
        print(f" - Resume from: {args.resume}")
    print("=========================================================")

    env = TankEnvironment(max_steps=args.max_steps)
    ga = GAPopulation(args.population, adapter.output_dim, [32, 24], 4)

    best_overall = -float("inf")  # best validation score
    val_seeds = [10_000_000 + i for i in range(args.val_maps)]  # same maps every generation
    model_path = os.path.join(args.save_dir, "best_model.npz")

    base_model = None
    if args.resume and os.path.exists(args.resume):
        try:
            base_model = SimpleMLP.load(args.resume)
            if base_model.input_dim == adapter.output_dim and base_model.hidden_dims == [32, 24]:
                ga.seed_with_model(base_model)
                print(f"[*] Resumed and seeded population from {args.resume}")
            else:
                print(f"[!] Architecture mismatch for {args.resume}, starting fresh.")
                base_model = None
        except Exception as e:
            print(f"[!] Could not load {args.resume}: {e}")

    if self_play:
        initial_opp_model = base_model if base_model is not None else ga.population[0]
        champ_pool = [MLPAgent(initial_opp_model, adapter)]
        opponent = champ_pool
        base_val = evaluate_individual(initial_opp_model, adapter, benchmark_bot, env, val_seeds)
        best_overall = base_val
        print(f"[*] Baseline validation vs rule_based: {base_val:.2f}")
    else:
        if base_model is not None:
            base_val = evaluate_individual(base_model, adapter, opponent, env, val_seeds)
            best_overall = base_val
            print(f"[*] Baseline validation score to beat: {base_val:.2f}")

    # Save initial untrained Gen 0 agent only if starting fresh
    if args.start_gen == 0:
        ga.population[0].save(os.path.join(args.save_dir, "model_gen_0.npz"))
        write_checkpoint_agent(args.save_dir, adapter_cls, "model_gen_0.npz", "agent_gen_0.py")

    start = time.time()
    for step in range(1, args.generations + 1):
        gen = args.start_gen + step
        seeds = [map_rng.randrange(1_000_000_000) for _ in range(args.rounds)]
        fitnesses = [evaluate_individual(ind, adapter, opponent, env, seeds) for ind in ga.population]

        best_ind, best_fit, mean_fit = ga.evolve(fitnesses)
        line = f"Gen {gen:03d}/{total_target_gens:03d} | Best: {best_fit:8.2f} | Mean: {mean_fit:8.2f}"

        # Evaluate against the fixed external benchmark to measure true objective progress
        test_bot = benchmark_bot if self_play else opponent
        val = evaluate_individual(best_ind, adapter, test_bot, env, val_seeds)
        line += f" | Val: {val:8.2f}"
        if val > best_overall:
            best_overall = val
            best_ind.save(model_path)
            line += " *"
        print(line)

        if self_play:
            new_champ = MLPAgent(best_ind, adapter)
            if len(champ_pool) < 5:
                champ_pool.append(new_champ)
            else:
                champ_pool.pop(1)  # keep earliest champion + recent champions
                champ_pool.append(new_champ)
            opponent = champ_pool

        if gen % args.checkpoint_interval == 0 or step == args.generations:
            model_fname = f"model_gen_{gen}.npz"
            agent_fname = f"agent_gen_{gen}.py"
            best_ind.save(os.path.join(args.save_dir, model_fname))
            write_checkpoint_agent(args.save_dir, adapter_cls, model_fname, agent_fname)

    write_agent_file(args.save_dir, adapter_cls)
    print("=========================================================")
    print(f" Done in {time.time() - start:.1f}s. Best {"fitness" if self_play else "validation score"}: {best_overall:.2f}")
    print(f" Agent: {os.path.join(args.save_dir, 'agent.py')}  (model: {model_path})")
    print(f" Test it: python python/referee.py {os.path.join(args.save_dir, 'agent.py')} rule_based")
    print("=========================================================")


if __name__ == "__main__":
    main()
